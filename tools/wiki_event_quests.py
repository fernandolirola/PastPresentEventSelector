"""Regenerates Events/WikiEventQuests.cs from the community wiki Events page.

Usage: python -I tools/wiki_event_quests.py
Reads the section anchors from Events/EventCatalog.cs (WikiSections) and lists every
"Quest [[Name]]" link found in each event's section.
"""
import json
import pathlib
import re
import urllib.parse
import urllib.request

ROOT = pathlib.Path(__file__).resolve().parent.parent
API = "https://escapefromtarkov.fandom.com/api.php?action=parse&page=Events&prop=wikitext&format=json"
# these wiki sections describe another year's version of the event, not what SPT runs
SKIP = {"halloween", "newyears", "aprilfools"}
# wiki link targets that point to a non-quest page
FIXES = {"bloodhounds": ["Bloodhounds (quest)"]}


def main():
    req = urllib.request.Request(API, headers={"User-Agent": "Mozilla/5.0"})
    text = json.load(urllib.request.urlopen(req))["parse"]["wikitext"]["*"]
    catalog = (ROOT / "Events" / "EventCatalog.cs").read_text(encoding="utf-8")
    block = catalog.split("WikiSections")[1].split("};")[0]
    sections = dict(re.findall(r'\["(\w+)"\] = "([^"]+)"', block))

    heads = [(m.start(), m.group(1).strip(), len(m.group(0)) - len(m.group(0).lstrip("=")))
             for m in re.finditer(r"^(={2,3})([^=].*?)\1\s*$", text, re.M)]
    heads = [(pos, re.match(r"^=+(.*?)=+\s*$", text[pos:text.index("\n", pos)]).group(1).strip(), lvl)
             for pos, _, lvl in heads]

    def body(anchor):
        title = urllib.parse.unquote(anchor).replace("_", " ")
        for i, (pos, head, level) in enumerate(heads):
            if head == title:
                end = next((p for p, _, l in heads[i + 1:] if l <= level), len(text))
                return text[pos:end]
        return None

    result = {}
    for event_id, anchor in sections.items():
        if event_id in SKIP:
            continue
        section = body(anchor)
        if section is None:
            print("section not found:", event_id)
            continue
        names = []
        for m in re.finditer(r"[Qq]uest\s*\[\[([^\]|#]+)", section):
            name = m.group(1).strip()
            if name not in names:
                names.append(name)
        result[event_id] = FIXES.get(event_id, names)

    lines = [
        "namespace PPES.Events;",
        "",
        "// Generated by tools/wiki_event_quests.py from the community wiki Events page.",
        "internal static class WikiEventQuests",
        "{",
        "    public static readonly Dictionary<string, string[]> ByEvent = new(StringComparer.OrdinalIgnoreCase)",
        "    {",
    ]
    for event_id, names in result.items():
        if names:
            lines.append(f"        [{json.dumps(event_id)}] = [{', '.join(json.dumps(n, ensure_ascii=False) for n in names)}],")
    lines += ["    };", "}", ""]
    (ROOT / "Events" / "WikiEventQuests.cs").write_text("\n".join(lines), encoding="utf-8")
    print(sum(len(v) for v in result.values()), "quests in", sum(1 for v in result.values() if v), "events")


if __name__ == "__main__":
    main()
